"""The .env file: where it lives, what it holds, and when a secret is not good enough.

Separate from app/config.py on purpose. config.py refuses to load without a valid
.env, and ``python -m app.cli init`` has to run before one exists, so what they
share must be importable with no settings at all. Standard library only.
"""

from __future__ import annotations

import os
import secrets
import subprocess
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]

# The three values that must be real secrets. Each is random per install.
SECRET_FIELDS = ("SECRET_KEY", "JWT_SECRET_KEY", "ENCRYPTION_SALT")
MIN_SECRET_LENGTH = 32

# Anything starting like this was copied from an example, not generated.
_PLACEHOLDER_PREFIXES = (
    "your-", "your_", "change", "replace", "placeholder", "example", "secret-key", "secret_key", "dummy",
)
# A token of 32+ random characters always has more distinct characters than this.
_MIN_DISTINCT_CHARACTERS = 10

ENV_SECRETS_TEMPLATE = """\
# Generated by `python -m app.cli init`. Keep this file private (mode 600).

# Encrypts the API keys stored in the database. Losing it makes them unreadable.
SECRET_KEY={secret_key}
# Signs sessions. Rotating it only signs you out.
JWT_SECRET_KEY={jwt_secret_key}
# HKDF salt for the stored API keys, random per install.
ENCRYPTION_SALT={encryption_salt}
"""

ENV_TEMPLATE = ENV_SECRETS_TEMPLATE + """
DATA_DIR=./data
HOST=127.0.0.1
PORT=8000
# Comma-separated proxy addresses allowed to set X-Forwarded-For and -Proto. Empty means
# local use. See docs/DEPLOYMENT.md to publish on a domain.
TRUSTED_PROXIES=
DEBUG=false
LOG_LEVEL=INFO
"""


def env_file_path() -> Path:
    """backend/.env, unless SKETCHMAKER_ENV_FILE points somewhere else."""
    override = os.environ.get("SKETCHMAKER_ENV_FILE")
    return Path(override).expanduser().resolve() if override else BACKEND_DIR / ".env"


def secret_problem(value: str | None) -> str | None:
    """Why this value cannot be used as a secret, or None when it can."""
    if not value:
        return "is missing"
    if len(value) < MIN_SECRET_LENGTH:
        return f"is shorter than {MIN_SECRET_LENGTH} characters"
    lowered = value.lower()
    if lowered.startswith(_PLACEHOLDER_PREFIXES) or len(set(lowered)) < _MIN_DISTINCT_CHARACTERS:
        return "looks like a placeholder"
    return None


def new_secret() -> str:
    """A fresh random token that passes secret_problem."""
    while True:
        value = secrets.token_urlsafe(48)
        if secret_problem(value) is None:
            return value


def write_new_env_file(path: Path, secrets_only: bool = False) -> None:
    """Create the .env file with fresh secrets, mode 600. Never overwrites.

    O_EXCL makes the refusal atomic: two simultaneous runs cannot both write it,
    and the file is never visible with looser permissions.

    secrets_only leaves out the other settings, for deployments that set them in the
    environment or append their own: the file wins over the environment, so a HOST
    written here could not be overridden.
    """
    template = ENV_SECRETS_TEMPLATE if secrets_only else ENV_TEMPLATE
    text = template.format(
        secret_key=new_secret(), jwt_secret_key=new_secret(), encryption_salt=new_secret(),
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(text)
    _private_on_windows(path)


def _private_on_windows(path: Path) -> None:
    """Windows ignores the mode above, so limit the file to this user with its own tool.
    Best effort: a failure leaves the permissions of the folder it is in."""
    user = os.environ.get("USERNAME")
    if os.name != "nt" or not user:
        return
    try:
        subprocess.run(["icacls", str(path), "/inheritance:r", "/grant:r", f"{user}:F"],
                       capture_output=True, check=False, timeout=15)
    except (OSError, subprocess.SubprocessError):
        pass
